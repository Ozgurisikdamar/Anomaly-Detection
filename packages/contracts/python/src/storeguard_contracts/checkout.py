"""Self-checkout session and simulated integration signals.

Every POS/scanner/scale signal in this demo is generated by a simulator and
carries ``simulated=True``. Video alone cannot know an item was scanned or
weighed — that knowledge only ever comes from an integration, and in Phase 0
that integration is simulated.
"""

from __future__ import annotations

from datetime import UTC, datetime

from pydantic import BaseModel, Field

from storeguard_contracts.enums import CheckoutState


def _utcnow() -> datetime:
    return datetime.now(tz=UTC)


class ScanEvent(BaseModel):
    """A scanner/POS scan. SIMULATED in Phase 0."""

    scan_id: str
    terminal_id: str
    session_id: str
    sku: str
    quantity: int = 1
    occurred_at: datetime = Field(default_factory=_utcnow)
    voided: bool = False
    simulated: bool = True


class ScaleEvent(BaseModel):
    """A scale reading. SIMULATED in Phase 0."""

    scale_id: str
    terminal_id: str
    session_id: str
    stable_weight_g: float | None = None
    expected_weight_g: float | None = None
    placement: str = Field(default="placed", description="placed | removed")
    calibration_ok: bool = True
    occurred_at: datetime = Field(default_factory=_utcnow)
    simulated: bool = True


class TransactionEvent(BaseModel):
    """A terminal/transaction lifecycle event. SIMULATED in Phase 0."""

    transaction_id: str
    terminal_id: str
    session_id: str
    kind: str = Field(
        description=(
            "payment_authorized | payment_declined | completed | void | "
            "attendant_override"
        )
    )
    occurred_at: datetime = Field(default_factory=_utcnow)
    simulated: bool = True


class CheckoutSession(BaseModel):
    """Independent per-terminal state machine snapshot."""

    terminal_id: str
    store_id: str
    session_id: str | None = None
    state: CheckoutState = CheckoutState.IDLE
    scans: list[ScanEvent] = Field(default_factory=list)
    scale_events: list[ScaleEvent] = Field(default_factory=list)
    transaction_events: list[TransactionEvent] = Field(default_factory=list)
    updated_at: datetime = Field(default_factory=_utcnow)
    # Marks the whole feed as simulated for the UI banner.
    simulated: bool = True
